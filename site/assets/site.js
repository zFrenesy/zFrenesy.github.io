/* Progressive enhancement; browsing and source downloads work without JavaScript. */
(function () {
  'use strict';
  var root = document.documentElement;
  var themeButton = document.querySelector('[data-theme-toggle]');
  var media = window.matchMedia('(prefers-color-scheme: dark)');
  var storedTheme = null;
  try { storedTheme = localStorage.getItem('we-solve-theme'); } catch (_) { /* Storage may be disabled. */ }
  if (storedTheme === 'dark' || storedTheme === 'light') root.dataset.theme = storedTheme;

  function isDark() {
    return root.dataset.theme ? root.dataset.theme === 'dark' : media.matches;
  }
  function updateThemeLabel() {
    if (!themeButton) return;
    var label = 'Switch to ' + (isDark() ? 'light' : 'dark') + ' appearance';
    themeButton.setAttribute('aria-label', label);
    themeButton.querySelector('[data-theme-label]').textContent = label;
  }
  if (themeButton) {
    themeButton.hidden = false;
    updateThemeLabel();
    themeButton.addEventListener('click', function () {
      root.dataset.theme = isDark() ? 'light' : 'dark';
      try { localStorage.setItem('we-solve-theme', root.dataset.theme); } catch (_) { /* Optional preference. */ }
      updateThemeLabel();
    });
    if (media.addEventListener) media.addEventListener('change', updateThemeLabel);
  }

  var status = document.getElementById('interaction-status');
  document.querySelectorAll('[data-copy-target]').forEach(function (button) {
    if (!navigator.clipboard || !navigator.clipboard.writeText) return;
    button.hidden = false;
    button.addEventListener('click', function () {
      var target = document.getElementById(button.dataset.copyTarget);
      if (!target) return;
      navigator.clipboard.writeText(target.textContent).then(function () {
        if (status) status.textContent = 'Citation copied to clipboard.';
        button.textContent = 'Copied';
        window.setTimeout(function () { button.textContent = 'Copy'; }, 2000);
      }).catch(function () {
        if (status) status.textContent = 'Copy was unavailable. Select the citation text to copy it.';
      });
    });
  });

  var menu = document.querySelector('.discipline-menu');
  if (menu) {
    document.addEventListener('click', function (event) {
      if (!menu.contains(event.target)) menu.open = false;
    });
    menu.addEventListener('keydown', function (event) {
      if (event.key === 'Escape') {
        menu.open = false;
        menu.querySelector('summary').focus();
      }
    });
  }

  // Opening a build-generated reference may require expanding a details element.
  // The target and its caption are left exactly as generated by the build.
  function revealHash() {
    if (!window.location.hash) return;
    var identifier;
    try { identifier = decodeURIComponent(window.location.hash.slice(1)); } catch (_) { return; }
    var target = document.getElementById(identifier);
    if (!target) return;
    var parent = target.parentElement;
    var expanded = false;
    while (parent) {
      if (parent.tagName === 'DETAILS' && !parent.open) { parent.open = true; expanded = true; }
      parent = parent.parentElement;
    }
    if (expanded) target.scrollIntoView({ block: 'start' });
  }
  window.addEventListener('hashchange', revealHash);
  revealHash();
}());
